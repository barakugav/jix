//! F027 internal repro: the shared test comparators are weaker than documented.
//!
//! `crate::util::assert_array_matches`, `same_value`, `assert_same_elements` and the reduction
//! tests' `ReductionCompare` / `reduction_shape_strategy` are `pub(crate)` / private, so this runs
//! in a scratch COPY of the crate (never the shared tree). It is mounted inside
//! `jix/src/ops/reduction.rs`'s `mod tests` (as a child module, so it can reach the private
//! `ReductionCompare` and `reduction_shape_strategy`) with:
//!
//! ```text
//! #[path = "<abs path>/F027_internal.rs"] mod f027;
//! ```
//!
//! Every `f027_helper_*` test asserts the CORRECT (documented / intended) behavior of a helper, so
//! it fails while the gap exists. `f027_mutation_demo_*` instead documents the impact: it only
//! fails in the scratch copy whose f32/f64 `neg_bulk` was mutated (see F027.md), and shows that the
//! existing helper-based checks accept that wrong kernel.
//!
//! Run: CARGO_TARGET_DIR=bug-hunt/runs/2026-10-29-batch6/scratch/target-f027 cargo test \
//!   --manifest-path bug-hunt/runs/2026-10-29-batch6/scratch/crate-f027/Cargo.toml --all-features \
//!   --lib f027 -- --nocapture --test-threads 1

use crate::scalar::bool8;
use crate::util::{assert_array_matches, assert_same_elements, same_value};
use crate::Array;
use ndarray::{array, ArrayD, Ix1, IxDyn};
use std::panic::{catch_unwind, AssertUnwindSafe};

/// Whether `f` panics (an assertion helper rejecting its input).
fn rejects(f: impl FnOnce()) -> bool {
    catch_unwind(AssertUnwindSafe(f)).is_err()
}

/// test_util.rs:886-887 documents assert_array_matches as comparing "bit-for-bit".
#[test]
fn f027_helper_assert_array_matches_rejects_signed_zero() {
    let actual = Array::compact_ndarray(&array![-0.0f64, 1.0]).unwrap();
    assert!(
        rejects(|| assert_array_matches(&actual, &array![0.0f64, 1.0])),
        "assert_array_matches accepted actual -0.0 for expected +0.0 (doc: bit-for-bit)"
    );
}

/// A bit-for-bit comparison must accept a bit-identical NaN.
#[test]
fn f027_helper_assert_array_matches_accepts_identical_nan() {
    let actual = Array::compact_ndarray(&array![f64::NAN, 1.0]).unwrap();
    assert!(
        !rejects(|| assert_array_matches(&actual, &array![f64::NAN, 1.0])),
        "assert_array_matches rejected a bit-identical NaN (doc: bit-for-bit)"
    );
}

/// bool8(2) / bool8(0xFF) are not bit-identical to bool8::TRUE (byte 1).
#[test]
fn f027_helper_assert_array_matches_rejects_noncanonical_bool8() {
    let actual = Array::compact_ndarray(&array![bool8(2), bool8(0xFF)]).unwrap();
    assert!(
        rejects(|| assert_array_matches(&actual, &array![bool8::TRUE, bool8::TRUE])),
        "assert_array_matches accepted bool8 bytes 2 and 0xFF for bool8::TRUE (doc: bit-for-bit)"
    );
}

/// same_value / assert_same_elements (all SIMD-body tests but op2's div_rem) ignore the sign of
/// zero, so a SIMD lane returning +0.0 where the scalar path returns -0.0 passes.
#[test]
fn f027_helper_same_value_distinguishes_signed_zero() {
    assert!(!same_value(&-0.0f32, &0.0f32), "same_value(-0.0, +0.0) is true");
    assert!(
        rejects(|| assert_same_elements([0.0f32; 4], |_| -0.0f32, "neg lane")),
        "assert_same_elements accepted +0.0 lanes where -0.0 was expected"
    );
}

/// The f32 reduction comparator (rtol 1e-3, atol 0.1, reduction.rs:3505-3509) is also used for
/// `max`/`min`, which select an input element and should match exactly.
#[test]
fn f027_helper_reduction_f32_max_compare_rejects_other_element() {
    use super::ReductionCompare;
    let nd = array![1.0f32, 1.05].into_dyn();
    let za = Array::compact_ndarray(&nd).unwrap();
    let actual = za.view().max(0usize); // = 1.05
    let wrong: ArrayD<f32> = ndarray::arr0(1.0f32).into_dyn(); // the other element
    assert_eq!(actual.to_ndarray::<IxDyn>().unwrap()[[]], 1.05f32);
    assert!(
        rejects(|| <f32 as ReductionCompare>::assert_matches(&actual, &wrong)),
        "the f32 max comparator accepted 1.0 for a max of 1.05 (a different input element)"
    );
}

/// reduction_shape_strategy (reduction.rs:3568) never draws a zero-length dim (or a 0-d shape),
/// so empty reductions (K62) are never generated by the reduction proptests.
#[test]
fn f027_helper_reduction_shape_strategy_draws_empty_shapes() {
    use proptest::strategy::{Strategy, ValueTree};
    let mut runner = proptest::test_runner::TestRunner::deterministic();
    let strategy = super::reduction_shape_strategy();
    let (mut zero_len, mut zero_d, n) = (0usize, 0usize, 20_000usize);
    for _ in 0..n {
        let shape = strategy.new_tree(&mut runner).unwrap().current();
        zero_len += shape.contains(&0) as usize;
        zero_d += shape.is_empty() as usize;
    }
    println!("reduction_shape_strategy: {n} draws, {zero_len} with a zero-length dim, {zero_d} 0-d");
    assert!(zero_len > 0, "no zero-length dim in {n} draws");
}

/// Impact demo (only meaningful in the scratch copy whose f32/f64 `neg_bulk` was mutated to
/// `(x * -1.0) + 0.0`, i.e. -(+0.0) == +0.0 in the SIMD body): the existing helper accepts the
/// wrong result, a bit check does not. In the unmutated tree this test passes.
#[test]
fn f027_mutation_demo_neg_of_positive_zero() {
    let n = 256;
    let a = Array::compact_ndarray(&ndarray::Array1::<f32>::zeros(n)).unwrap();
    let neg = -a.view();
    let expected = ndarray::Array1::<f32>::from_elem(n, -0.0);
    // The helper used by every op proptest: passes either way.
    assert_array_matches(&neg, &expected);
    let got = neg.to_ndarray::<Ix1>().unwrap();
    let bad = got.iter().filter(|x| x.to_bits() != (-0.0f32).to_bits()).count();
    assert_eq!(bad, 0, "neg(+0.0) returned +0.0 for {bad} of {n} elements, but assert_array_matches passed");
}
