"""Generate `context/api_index.md`: every public name of the Rust crate and the Python package.

The index is built from the build outputs, not from the sources, so it lists exactly what users
see - including items generated by macros. Reviewers use it to spot stale names in the docs.

Requires `cargo doc --all-features` in `jix` and `maturin develop` in `jix-py` to have run.

Usage (from the repo root):
    python scripts/docs_review/gen_api_index.py
"""

import re
import textwrap
from pathlib import Path

import jix

REPO = Path(__file__).resolve().parents[2]
RUSTDOC = REPO / "jix/target/doc/jix"
OUT = Path(__file__).resolve().parent / "context/api_index.md"

# Methods rustdoc lists on `Array` that come from std blanket impls.
STD_METHODS = {
    "borrow",
    "borrow_mut",
    "clone",
    "clone_from",
    "clone_into",
    "clone_to_uninit",
    "fmt",
    "from",
    "into",
    "simd_from",
    "simd_into",
    "to_owned",
    "try_from",
    "try_into",
    "type_id",
}


def wrap(names: list[str]) -> str:
    return textwrap.fill(", ".join(f"`{name}`" for name in names), width=100, break_on_hyphens=False)


def methods(page: str) -> list[str]:
    html = (RUSTDOC / page).read_text(encoding="utf-8")
    return sorted(set(re.findall(r'id="method\.(\w+)"', html)) - STD_METHODS)


def rust_sections() -> list[str]:
    html = (RUSTDOC / "all.html").read_text(encoding="utf-8")
    out = []
    for kind, items in re.findall(r'<h3 id="\w+">([^<]+)</h3><ul class="all-items">(.*?)</ul>', html, re.DOTALL):
        names = re.findall(r'<a href="[^"]+">([^<]+)</a>', items)
        out.append(f"### {kind}\n\n{wrap(names)}\n")
    out.append(f"### Methods of `Array`\n\n{wrap(methods('struct.Array.html'))}\n")
    out.append(f"### Methods of `ArrayParams`\n\n{wrap(methods('struct.ArrayParams.html'))}\n")
    out.append(f"### Methods of `dtype::Dtype`\n\n{wrap(methods('dtype/struct.Dtype.html'))}\n")
    return out


def python_sections() -> list[str]:
    def public(obj) -> list[str]:
        return sorted(name for name in dir(obj) if not name.startswith("_"))

    exported = sorted(name for name in jix.__all__ if not name.startswith("_"))
    functions = [name for name in exported if name != "Array"]
    dunders = sorted(
        name for name in vars(jix.Array) if name.startswith("__") and name not in ("__doc__", "__module__")
    )
    return [
        f"### Module functions (`jix.__all__`, aliases included)\n\n{wrap(functions)}\n",
        f"### Methods and properties of `jix.Array`\n\n{wrap(public(jix.Array))}\n",
        f"### Operators of `jix.Array`\n\n{wrap(dunders)}\n",
    ]


def main():
    parts = [
        "# API index\n",
        "Generated by `scripts/docs_review/gen_api_index.py` from the build outputs. Do not edit.\n",
        "A name that the docs mention and this index lacks is either private or stale.\n",
        f"## Rust crate `jix` (all features)\n\n{'\n'.join(rust_sections())}",
        f"## Python package `jix` {jix.__version__}\n\n{'\n'.join(python_sections())}",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
